"""Build the versioned, same-origin offline dependency list for preview-5."""
from pathlib import Path
import argparse
import hashlib
import json
import re
import urllib.parse

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'assets/goi-viet/map-surroundings-preview/offline-manifest-5.js'
WORKER = ROOT / 'preview-5-offline-worker.js'
PATTERN = re.compile(r'''(?:["'`(]|\b(?=assets/))((?:assets/|\.\.?/)?[\w./%&=+?()@ -]+\.(?:js|css|webp|png|jpe?g|svg|woff2?|ttf|mp3|mp4|ico|json)(?:\?[^"'`\s<>)]*)?)''')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='fail if the generated manifest is stale; write nothing')
    args = parser.parse_args()
    pending = [ROOT / 'map-surroundings-preview-5.html']
    # Computed URLs: runtime assets only, excluding working originals/references.
    for directory, extensions in [
        ('assets/goi-viet/map-surroundings-preview/natural', {'.js', '.webp', '.svg'}),
        ('assets/goi-viet/map-surroundings-preview/landmarks', {'.svg'}),
        ('assets/goi-viet/books-5/postcards', {'.webp'}),
    ]:
        pending.extend(f for f in (ROOT / directory).rglob('*') if f.is_file() and f.suffix in extensions)
    catalog = ROOT / 'assets/goi-viet/station-photos-5/catalog.json'
    pending.append(catalog)
    pending.extend(ROOT / photo['src'] for photo in json.loads(catalog.read_text(encoding='utf-8'))['photos'] if photo.get('src'))
    seen = set()
    while pending:
        file = pending.pop().resolve()
        if file in seen or file in [OUTPUT, WORKER] or not file.is_relative_to(ROOT): continue
        seen.add(file)
        if file.suffix not in {'.html', '.js', '.css', '.json'}: continue
        for match in PATTERN.finditer(file.read_text(encoding='utf-8', errors='replace')):
            raw = urllib.parse.unquote(match.group(1).split('?')[0])
            for candidate in [ROOT / raw, file.parent / raw, ROOT / 'assets/goi-viet' / raw]:
                if candidate.is_file() and candidate.resolve().is_relative_to(ROOT):
                    pending.append(candidate)
                    break
    paths = sorted(file.relative_to(ROOT).as_posix() for file in seen)
    digest = hashlib.sha256(WORKER.read_bytes())
    hashes = {}
    for name in paths:
        digest.update(name.encode('utf-8'))
        content = (ROOT / name).read_bytes()
        digest.update(content)
        hashes[name] = hashlib.sha256(content).hexdigest()
    manifest = {'version': digest.hexdigest()[:16], 'bytes': sum(f.stat().st_size for f in seen), 'files': paths, 'hashes': hashes}
    generated = '/* Generated by tools/build-preview-5-offline.py. Rebuild after preview-5 asset changes. */\nself.GoiVietOfflineManifest = ' + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n'
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != generated:
            print('FAIL: offline manifest is stale. Run python tools/build-preview-5-offline.py')
            raise SystemExit(1)
        print('PASS: offline manifest is up to date; no files written.')
        return
    OUTPUT.write_text(generated, encoding='utf-8')
    print('Offline manifest:', len(paths), 'resources;', round(manifest['bytes'] / 1e6, 2), 'MB;', manifest['version'])


if __name__ == '__main__': main()
